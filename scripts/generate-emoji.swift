// Regenerates Extensions/emoji/emoji.tsv from Unicode's emoji-test.txt and
// CLDR's English annotations (both Unicode License v3, see
// Extensions/emoji/LICENSE-UNICODE.txt), plus the Slack/GitHub-style
// shortcodes from GitHub's gemoji (MIT, see LICENSE-GEMOJI.txt). Run it from
// the repo root:
//
//   swift scripts/generate-emoji.swift
//
// Output, one emoji per line, tab-separated:
//   emoji  name  group  emoji-version  keywords(,)  skin-tone variants(,)  shortcodes(,)
// The variants are the five single-tone versions, light to dark.
import Foundation

let emojiVersion = "18.0.0"
let cldrVersion = "48.2.3"
let gemojiVersion = "v4.1.0"
let sources = [
    "test": "https://www.unicode.org/Public/\(emojiVersion)/emoji/emoji-test.txt",
    "annotations": "https://raw.githubusercontent.com/unicode-org/cldr-json/\(cldrVersion)/cldr-json/cldr-annotations-full/annotations/en/annotations.json",
    "gemoji": "https://raw.githubusercontent.com/github/gemoji/\(gemojiVersion)/db/emoji.json",
    "derived": "https://raw.githubusercontent.com/unicode-org/cldr-json/\(cldrVersion)/cldr-json/cldr-annotations-derived-full/annotationsDerived/en/annotations.json",
]

func fetch(_ key: String) -> Data {
    let url = URL(string: sources[key]!)!
    guard let data = try? Data(contentsOf: url) else {
        FileHandle.standardError.write(Data("could not download \(url)\n".utf8))
        exit(1)
    }
    return data
}

/// emoji -> keywords, from CLDR (with and without variation selectors).
func keywords(_ data: Data, root: String) -> [String: [String]] {
    let json = try! JSONSerialization.jsonObject(with: data) as! [String: Any]
    let ann = (json[root] as! [String: Any])["annotations"] as! [String: [String: [String]]]
    var out: [String: [String]] = [:]
    for (k, v) in ann { out[k] = v["default"] ?? [] }
    return out
}

var cldr = keywords(fetch("annotations"), root: "annotations")
for (k, v) in keywords(fetch("derived"), root: "annotationsDerived") where cldr[k] == nil { cldr[k] = v }

var shortcodes: [String: [String]] = [:]
for e in try! JSONSerialization.jsonObject(with: fetch("gemoji")) as! [[String: Any]] {
    shortcodes[(e["emoji"] as! String).replacingOccurrences(of: "\u{FE0F}", with: "")] = e["aliases"] as? [String] ?? []
}

func lookup(_ e: String) -> [String] {
    cldr[e] ?? cldr[e.replacingOccurrences(of: "\u{FE0F}", with: "")] ?? []
}

struct Entry {
    var emoji: String
    var name: String
    var group: String
    var version: String
    var tones: [String?] = Array(repeating: nil, count: 5)
}

let toneNames = ["light skin tone", "medium-light skin tone", "medium skin tone", "medium-dark skin tone", "dark skin tone"]
var entries: [Entry] = []
var byName: [String: Int] = [:]
var group = ""
let text = String(decoding: fetch("test"), as: UTF8.self)
for line in text.split(separator: "\n") {
    if line.hasPrefix("# group: ") {
        group = String(line.dropFirst("# group: ".count))
        continue
    }
    guard !line.hasPrefix("#"), line.contains("; fully-qualified"), group != "Component",
          let hash = line.range(of: "# ") else { continue }
    // "😂 E0.6 face with tears of joy"
    let parts = line[hash.upperBound...].split(separator: " ", maxSplits: 2)
    guard parts.count == 3 else { continue }
    let emoji = String(parts[0])
    let version = String(parts[1].dropFirst())
    let name = String(parts[2])
    // "thumbs up: medium skin tone" is a variant of "thumbs up"; mixed
    // tones ("…: light skin tone, dark skin tone") are left out.
    if let colon = name.range(of: ": ", options: .backwards), let tone = toneNames.firstIndex(of: String(name[colon.upperBound...])) {
        if let base = byName[String(name[..<colon.lowerBound])] { entries[base].tones[tone] = emoji }
        continue
    }
    if name.contains("skin tone") { continue }
    byName[name] = entries.count
    entries.append(Entry(emoji: emoji, name: name, group: group, version: version))
}

var out = "# Generated by scripts/generate-emoji.swift from Unicode emoji \(emojiVersion), CLDR \(cldrVersion) and gemoji \(gemojiVersion). Do not edit.\n"
for e in entries {
    let nameWords = Set(e.name.lowercased().split(whereSeparator: { !$0.isLetter && !$0.isNumber }).map(String.init))
    // Keywords that only repeat the name add nothing to search.
    let kws = lookup(e.emoji).map { $0.lowercased() }.filter { !nameWords.contains($0) && $0 != e.name.lowercased() }
    let tones = e.tones.allSatisfy { $0 != nil } ? e.tones.map { $0! }.joined(separator: ",") : ""
    let clean = { (s: String) in s.replacingOccurrences(of: "\t", with: " ").replacingOccurrences(of: ",", with: " ") }
    let codes = shortcodes[e.emoji.replacingOccurrences(of: "\u{FE0F}", with: "")] ?? []
    out += [e.emoji, e.name, e.group, e.version, kws.map(clean).joined(separator: ","), tones,
            codes.joined(separator: ",")].joined(separator: "\t") + "\n"
}
let dest = URL(fileURLWithPath: "Extensions/emoji/emoji.tsv")
try! FileManager.default.createDirectory(at: dest.deletingLastPathComponent(), withIntermediateDirectories: true)
try! out.write(to: dest, atomically: true, encoding: .utf8)
print("wrote \(entries.count) emoji to \(dest.path)")
